-- OLOCATION v2 en Supabase (PostgreSQL) — PREPARADO, TODAVÍA NO APLICADO EN NINGÚN PROYECTO.
-- Equivalente a backend/db/migrations/001_stores.sql + el acceso con contraseña general.
-- Guía: docs/SUPABASE.md
--
-- Seguridad: las tablas tienen RLS activado y NINGUNA política, así que con la anon key no se
-- pueden leer ni escribir directamente. Todo pasa por 4 funciones RPC (SECURITY DEFINER):
--   verify_access(p_password)                       → { ok, token, expires_at } | { ok:false, error, message }
--   list_stores(p_token)                            → json[] de tiendas con change_count
--   list_store_location_changes(p_token, p_store_id) → json[] del historial (más reciente primero)
--   register_store_location(p_token, p_store_id, p_latitude, p_longitude, p_source, p_accuracy_m)
--                                                   → { store, change }
-- Los errores se lanzan con el código como mensaje (UNAUTHORIZED, STORE_NOT_FOUND,
-- VALIDATION_ERROR) y la explicación en español en HINT.

create extension if not exists pgcrypto with schema extensions;

create schema if not exists private;
revoke all on schema private from public;

-- ---------------------------------------------------------------------------
-- Tablas
-- ---------------------------------------------------------------------------

create table public.stores (
    id                   bigint generated by default as identity primary key,
    code                 text not null unique check (length(code) between 1 and 50),
    name                 text not null check (length(name) between 1 and 200),
    address              text,
    latitude             double precision check (latitude  between -90  and 90),
    longitude            double precision check (longitude between -180 and 180),
    location_updated_at  timestamptz,              -- último registro desde la app
    created_at           timestamptz not null default now(),
    constraint stores_coords_pair check ((latitude is null) = (longitude is null))
);
comment on table public.stores is 'Tiendas. latitude/longitude = coordenada vigente.';

-- Una fila por cada registro de ubicación hecho desde la app: su cantidad es el conteo de cambios.
create table public.store_location_changes (
    id                  bigint generated by default as identity primary key,
    store_id            bigint not null references public.stores(id) on delete cascade,
    latitude            double precision not null check (latitude  between -90  and 90),
    longitude           double precision not null check (longitude between -180 and 180),
    accuracy_m          double precision check (accuracy_m between 0 and 100000),
    source              text not null check (source in ('gps', 'map')),
    previous_latitude   double precision,
    previous_longitude  double precision,
    created_at          timestamptz not null default now()
);
create index store_location_changes_store_idx on public.store_location_changes (store_id, created_at desc);

alter table public.stores enable row level security;
alter table public.store_location_changes enable row level security;
revoke all on public.stores, public.store_location_changes from anon, authenticated;

-- Configuración y sesiones de acceso (fuera del esquema expuesto por la API).
create table private.app_settings (
    key         text primary key,
    value       text not null,
    updated_at  timestamptz not null default now()
);

create table private.access_sessions (
    token_hash  text primary key,                  -- SHA-256 del token; el token no se guarda
    created_at  timestamptz not null default now(),
    expires_at  timestamptz not null
);

create table private.failed_access (
    id          bigint generated always as identity primary key,
    ip          text not null,
    created_at  timestamptz not null default now()
);
create index failed_access_ip_idx on private.failed_access (ip, created_at);

-- Contraseña inicial: CAMBIARLA apenas se cree el proyecto (ver docs/SUPABASE.md).
insert into private.app_settings (key, value)
values ('access_password_hash', extensions.crypt('cambiar-esta-clave', extensions.gen_salt('bf')));

-- ---------------------------------------------------------------------------
-- Funciones internas
-- ---------------------------------------------------------------------------

create or replace function private.client_ip()
returns text
language sql
stable
set search_path = ''
as $$
  select coalesce(
    nullif(trim(split_part(
      (nullif(current_setting('request.headers', true), '')::json ->> 'x-forwarded-for'), ',', 1
    )), ''),
    'desconocida'
  );
$$;

create or replace function private.check_token(p_token text)
returns void
language plpgsql
stable
set search_path = ''
as $$
begin
  if p_token is null or not exists (
    select 1 from private.access_sessions
    where token_hash = encode(extensions.digest(p_token, 'sha256'), 'hex')
      and expires_at > now()
  ) then
    raise exception 'UNAUTHORIZED'
      using hint = 'El acceso venció o la contraseña cambió. Ingresala de nuevo.';
  end if;
end;
$$;

create or replace function private.store_json(p_store_id bigint)
returns json
language sql
stable
set search_path = ''
as $$
  select json_build_object(
    'id', s.id, 'code', s.code, 'name', s.name, 'address', s.address,
    'latitude', s.latitude, 'longitude', s.longitude,
    'location_updated_at', s.location_updated_at,
    'change_count', (select count(*) from public.store_location_changes c where c.store_id = s.id)
  )
  from public.stores s
  where s.id = p_store_id;
$$;

