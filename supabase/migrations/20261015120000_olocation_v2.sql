-- No lanza excepción ante contraseña incorrecta: así el intento fallido queda registrado
-- (una excepción desharía el INSERT) y sirve para frenar ataques de fuerza bruta.
create or replace function public.verify_access(p_password text)
returns json
language plpgsql
volatile
security definer
set search_path = ''
as $$
declare
  v_ip      text := private.client_ip();
  v_hash    text;
  v_token   text;
  v_expires timestamptz := now() + interval '365 days';
begin
  if (select count(*) from private.failed_access
      where ip = v_ip and created_at > now() - interval '15 minutes') >= 10 then
    return json_build_object('ok', false, 'error', 'TOO_MANY_ATTEMPTS',
      'message', 'Demasiados intentos fallidos. Intentá de nuevo en unos minutos.');
  end if;

  select value into v_hash from private.app_settings where key = 'access_password_hash';
  if v_hash is null or coalesce(p_password, '') = ''
     or extensions.crypt(p_password, v_hash) <> v_hash then
    insert into private.failed_access (ip) values (v_ip);
    delete from private.failed_access where created_at < now() - interval '1 day';
    return json_build_object('ok', false, 'error', 'INVALID_PASSWORD', 'message', 'Contraseña incorrecta.');
  end if;

  delete from private.failed_access where ip = v_ip;
  delete from private.access_sessions where expires_at <= now();
  v_token := encode(extensions.gen_random_bytes(32), 'hex');
  insert into private.access_sessions (token_hash, expires_at)
  values (encode(extensions.digest(v_token, 'sha256'), 'hex'), v_expires);
  return json_build_object('ok', true, 'token', v_token, 'expires_at', v_expires);
end;
$$;

create or replace function public.list_stores(p_token text)
returns json
language plpgsql
stable
security definer
set search_path = ''
as $$
begin
  perform private.check_token(p_token);
  -- Un único JSON (no "setof") para no chocar con el límite de filas de la API de Supabase.
  return coalesce((
    select json_agg(private.store_json(s.id) order by lower(s.name), s.code)
    from public.stores s
  ), '[]'::json);
end;
$$;

create or replace function public.list_store_location_changes(p_token text, p_store_id bigint)
returns json
language plpgsql
stable
security definer
set search_path = ''
as $$
begin
  perform private.check_token(p_token);
  if not exists (select 1 from public.stores where id = p_store_id) then
    raise exception 'STORE_NOT_FOUND' using hint = format('No existe una tienda con id %s.', p_store_id);
  end if;
  return coalesce((
    select json_agg(row_to_json(c) order by c.created_at desc, c.id desc)
    from public.store_location_changes c
    where c.store_id = p_store_id
  ), '[]'::json);
end;
$$;

create or replace function public.register_store_location(
  p_token      text,
  p_store_id   bigint,
  p_latitude   double precision,
  p_longitude  double precision,
  p_source     text,
  p_accuracy_m double precision default null
)
returns json
language plpgsql
volatile
security definer
set search_path = ''
as $$
declare
  v_store  public.stores%rowtype;
  v_change public.store_location_changes%rowtype;
begin
  perform private.check_token(p_token);

  if p_latitude is null or p_latitude not between -90 and 90 or p_latitude = 'NaN'::float8 then
    raise exception 'VALIDATION_ERROR' using hint = 'latitude: debe estar entre -90 y 90.';
  end if;
  if p_longitude is null or p_longitude not between -180 and 180 or p_longitude = 'NaN'::float8 then
    raise exception 'VALIDATION_ERROR' using hint = 'longitude: debe estar entre -180 y 180.';
  end if;
  if p_source is null or p_source not in ('gps', 'map') then
    raise exception 'VALIDATION_ERROR' using hint = 'source: debe ser "gps" o "map".';
  end if;
  if p_accuracy_m is not null and (p_accuracy_m not between 0 and 100000 or p_accuracy_m = 'NaN'::float8) then
    raise exception 'VALIDATION_ERROR' using hint = 'accuracyM: debe estar entre 0 y 100000.';
  end if;

  -- FOR UPDATE: dos registros simultáneos de la misma tienda guardan bien la coordenada anterior.
  select * into v_store from public.stores where id = p_store_id for update;
  if not found then
    raise exception 'STORE_NOT_FOUND' using hint = format('No existe una tienda con id %s.', p_store_id);
  end if;

  insert into public.store_location_changes
    (store_id, latitude, longitude, accuracy_m, source, previous_latitude, previous_longitude)
  values
    (p_store_id, p_latitude, p_longitude, p_accuracy_m, p_source, v_store.latitude, v_store.longitude)
  returning * into v_change;

  update public.stores
  set latitude = p_latitude, longitude = p_longitude, location_updated_at = v_change.created_at
  where id = p_store_id;

  return json_build_object('store', private.store_json(p_store_id), 'change', row_to_json(v_change));
end;
$$;

-- Solo estas 4 funciones quedan expuestas a la app (rol anon).
revoke execute on all functions in schema private from public;
revoke execute on function public.verify_access(text) from public;
revoke execute on function public.list_stores(text) from public;
revoke execute on function public.list_store_location_changes(text, bigint) from public;
revoke execute on function public.register_store_location(text, bigint, double precision, double precision, text, double precision) from public;
grant execute on function public.verify_access(text) to anon, authenticated;
grant execute on function public.list_stores(text) to anon, authenticated;
grant execute on function public.list_store_location_changes(text, bigint) to anon, authenticated;
grant execute on function public.register_store_location(text, bigint, double precision, double precision, text, double precision) to anon, authenticated;
