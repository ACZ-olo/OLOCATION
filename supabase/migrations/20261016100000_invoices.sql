-- OLOCATION v2 en Supabase: facturas (fotos) por tienda.
-- Equivalente a backend/db/migrations/002_invoices.sql + los endpoints de factura del backend
-- FastAPI (POST/GET/DELETE /api/v2/stores/{id}/invoices y la imagen).
--
-- Decisión de almacenamiento: como la app NO usa Supabase Auth (el acceso se valida con el token
-- propio en private.access_sessions), no se puede proteger un bucket de Storage con ese token.
-- Para que TODO pase por el mismo candado (private.check_token), la imagen se guarda como bytea
-- en la tabla y se entrega por RPC en base64, igual que el resto de los datos. El volumen de
-- facturas de esta app lo hace aceptable.
--
-- RPC nuevas (SECURITY DEFINER, exigen el token):
--   list_store_invoices(p_token, p_store_id)                         → json[] (más reciente primero, sin la imagen)
--   get_store_invoice_image(p_token, p_store_id, p_invoice_id)       → { mimeType, byteSize, imageBase64 }
--   register_store_invoice(p_token, p_store_id, p_mime_type, p_image_base64) → { store, invoice }
--   delete_store_invoice(p_token, p_store_id, p_invoice_id)          → { store }

-- ---------------------------------------------------------------------------
-- Tabla
-- ---------------------------------------------------------------------------

create table public.store_invoices (
    id          bigint generated by default as identity primary key,
    store_id    bigint not null references public.stores(id) on delete cascade,
    image       bytea  not null,                       -- la imagen tal cual (JPEG/PNG/WEBP)
    mime_type   text   not null check (mime_type in ('image/jpeg', 'image/png', 'image/webp')),
    byte_size   integer check (byte_size >= 0),
    created_at  timestamptz not null default now()
);
comment on table public.store_invoices is 'Facturas (fotos) por tienda. Una fila por factura.';
create index store_invoices_store_idx on public.store_invoices (store_id, created_at desc);

alter table public.store_invoices enable row level security;
revoke all on public.store_invoices from anon, authenticated;

-- ---------------------------------------------------------------------------
-- store_json: ahora incluye invoice_count y latest_invoice (sin los bytes de la imagen)
-- ---------------------------------------------------------------------------

create or replace function private.invoice_json(p_invoice public.store_invoices)
returns json
language sql
stable
set search_path = ''
as $$
  select json_build_object(
    'id', p_invoice.id,
    'store_id', p_invoice.store_id,
    'mime_type', p_invoice.mime_type,
    'byte_size', p_invoice.byte_size,
    'created_at', p_invoice.created_at
  );
$$;

create or replace function private.store_json(p_store_id bigint)
returns json
language sql
stable
set search_path = ''
as $$
  select json_build_object(
    'id', s.id, 'code', s.code, 'name', s.name, 'address', s.address,
    'latitude', s.latitude, 'longitude', s.longitude,
    'location_updated_at', s.location_updated_at,
    'change_count', (select count(*) from public.store_location_changes c where c.store_id = s.id),
    'invoice_count', (select count(*) from public.store_invoices v where v.store_id = s.id),
    'latest_invoice', (
      select private.invoice_json(v)
      from public.store_invoices v
      where v.store_id = s.id
      order by v.created_at desc, v.id desc
      limit 1
    )
  )
  from public.stores s
  where s.id = p_store_id;
$$;

-- ---------------------------------------------------------------------------
-- RPC
-- ---------------------------------------------------------------------------

create or replace function public.list_store_invoices(p_token text, p_store_id bigint)
returns json
language plpgsql
stable
security definer
set search_path = ''
as $$
begin
  perform private.check_token(p_token);
  if not exists (select 1 from public.stores where id = p_store_id) then
    raise exception 'STORE_NOT_FOUND' using hint = format('No existe una tienda con id %s.', p_store_id);
  end if;
  return coalesce((
    select json_agg(private.invoice_json(v) order by v.created_at desc, v.id desc)
    from public.store_invoices v
    where v.store_id = p_store_id
  ), '[]'::json);
end;
$$;

create or replace function public.get_store_invoice_image(
  p_token text, p_store_id bigint, p_invoice_id bigint
)
returns json
language plpgsql
stable
security definer
set search_path = ''
as $$
declare
  v_invoice public.store_invoices%rowtype;
begin
  perform private.check_token(p_token);
  select * into v_invoice from public.store_invoices
  where id = p_invoice_id and store_id = p_store_id;
  if not found then
    raise exception 'INVOICE_NOT_FOUND'
      using hint = format('La tienda %s no tiene una factura con id %s.', p_store_id, p_invoice_id);
  end if;
  return json_build_object(
    'mimeType', v_invoice.mime_type,
    'byteSize', v_invoice.byte_size,
    -- encode(..., 'base64') intercala saltos de línea cada 76 caracteres; se quitan para que
    -- la data URL que arma la app (data:...;base64,<...>) se renderice en <img>.
    'imageBase64', translate(encode(v_invoice.image, 'base64'), E'\n\r', '')
  );
end;
$$;

create or replace function public.register_store_invoice(
  p_token        text,
  p_store_id     bigint,
  p_mime_type    text,
  p_image_base64 text
)
returns json
language plpgsql
volatile
security definer
set search_path = ''
as $$
declare
  v_mime    text := lower(coalesce(p_mime_type, ''));
  v_image   bytea;
  v_size    integer;
  v_max     constant integer := 12 * 1024 * 1024;  -- 12 MB, igual que el backend FastAPI
  v_invoice public.store_invoices%rowtype;
begin
  perform private.check_token(p_token);

  if v_mime = 'image/jpg' then
    v_mime := 'image/jpeg';
  end if;
  if v_mime not in ('image/jpeg', 'image/png', 'image/webp') then
    raise exception 'VALIDATION_ERROR' using hint = 'La factura debe ser una imagen JPEG, PNG o WEBP.';
  end if;
  if p_image_base64 is null or length(p_image_base64) = 0 then
    raise exception 'VALIDATION_ERROR' using hint = 'La imagen está vacía.';
  end if;

  begin
    v_image := decode(p_image_base64, 'base64');
  exception when others then
    raise exception 'VALIDATION_ERROR' using hint = 'La imagen no está en base64 válido.';
  end;

  v_size := length(v_image);
  if v_size = 0 then
    raise exception 'VALIDATION_ERROR' using hint = 'La imagen está vacía.';
  end if;
  if v_size > v_max then
    raise exception 'VALIDATION_ERROR' using hint = 'La imagen supera el máximo de 12 MB.';
  end if;

  -- Verifica que el contenido coincida con el tipo declarado (magic numbers).
  -- substring(bytea ...) — no se usa left(), que en PostgreSQL solo acepta texto.
  if v_mime = 'image/jpeg' and substring(v_image from 1 for 3) <> '\xffd8ff'::bytea then
    raise exception 'VALIDATION_ERROR' using hint = 'El archivo no es un JPEG válido.';
  elsif v_mime = 'image/png' and substring(v_image from 1 for 8) <> '\x89504e470d0a1a0a'::bytea then
    raise exception 'VALIDATION_ERROR' using hint = 'El archivo no es un PNG válido.';
  elsif v_mime = 'image/webp' and (substring(v_image from 1 for 4) <> 'RIFF'::bytea
        or substring(v_image from 9 for 4) <> 'WEBP'::bytea) then
    raise exception 'VALIDATION_ERROR' using hint = 'El archivo no es un WEBP válido.';
  end if;

  if not exists (select 1 from public.stores where id = p_store_id) then
    raise exception 'STORE_NOT_FOUND' using hint = format('No existe una tienda con id %s.', p_store_id);
  end if;

  insert into public.store_invoices (store_id, image, mime_type, byte_size)
  values (p_store_id, v_image, v_mime, v_size)
  returning * into v_invoice;

  return json_build_object(
    'store', private.store_json(p_store_id),
    'invoice', private.invoice_json(v_invoice)
  );
end;
$$;

create or replace function public.delete_store_invoice(
  p_token text, p_store_id bigint, p_invoice_id bigint
)
returns json
language plpgsql
volatile
security definer
set search_path = ''
as $$
begin
  perform private.check_token(p_token);

  perform 1 from public.stores where id = p_store_id;
  if not found then
    raise exception 'STORE_NOT_FOUND' using hint = format('No existe una tienda con id %s.', p_store_id);
  end if;

  delete from public.store_invoices where id = p_invoice_id and store_id = p_store_id;
  if not found then
    raise exception 'INVOICE_NOT_FOUND'
      using hint = format('La tienda %s no tiene una factura con id %s.', p_store_id, p_invoice_id);
  end if;

  return json_build_object('store', private.store_json(p_store_id));
end;
$$;

