-- OLOCATION v2 en Supabase: módulo "Por factura".
-- Cada factura escaneada registra su cliente tal cual figura en la factura (código, nombre,
-- dirección y observaciones). Es un listado aparte de public.stores: un registro por código,
-- con su propia coordenada e historial (empieza sin coordenada). Si se escanea otra factura con
-- un código ya registrado, el registro queda como está.
--
-- RPC nuevas (SECURITY DEFINER, exigen el token):
--   list_invoice_stores(p_token)                                        → json[] (con change_count)
--   register_invoice_store(p_token, p_code, p_name, p_address, p_notes) → { store, created }
--   list_invoice_store_location_changes(p_token, p_store_id)            → json[] (más reciente primero)
--   register_invoice_store_location(p_token, p_store_id, p_latitude, p_longitude, p_source, p_accuracy_m)
--                                                                       → { store, change }
--   delete_invoice_store_location_change(p_token, p_store_id, p_change_id) → { store }
-- export_backup incluye "invoiceStores"; restore_backup lo restaura si el archivo lo trae (un
-- respaldo anterior, sin esa clave, no toca este módulo).

-- ---------------------------------------------------------------------------
-- Tablas
-- ---------------------------------------------------------------------------

create table public.invoice_stores (
    id                   bigint generated by default as identity primary key,
    code                 text not null check (length(code) between 1 and 50),
    name                 text not null check (length(name) between 1 and 200),
    address              text check (length(address) <= 500),
    notes                text check (length(notes) <= 2000),   -- observaciones de la factura
    latitude             double precision check (latitude  between -90  and 90),
    longitude            double precision check (longitude between -180 and 180),
    location_updated_at  timestamptz,
    created_at           timestamptz not null default now(),
    constraint invoice_stores_coords_pair check ((latitude is null) = (longitude is null))
);
comment on table public.invoice_stores is
  'Clientes registrados al escanear facturas (datos tal cual la factura). latitude/longitude = coordenada vigente.';
-- Un registro por código, sin importar los ceros a la izquierda (020210215 = 20210215).
create unique index invoice_stores_code_key on public.invoice_stores (ltrim(code, '0'));

create table public.invoice_store_location_changes (
    id                  bigint generated by default as identity primary key,
    invoice_store_id    bigint not null references public.invoice_stores(id) on delete cascade,
    latitude            double precision not null check (latitude  between -90  and 90),
    longitude           double precision not null check (longitude between -180 and 180),
    accuracy_m          double precision check (accuracy_m between 0 and 100000),
    source              text not null check (source in ('gps', 'map')),
    previous_latitude   double precision,
    previous_longitude  double precision,
    created_at          timestamptz not null default now()
);
create index invoice_store_location_changes_store_idx
  on public.invoice_store_location_changes (invoice_store_id, created_at desc);

alter table public.invoice_stores enable row level security;
alter table public.invoice_store_location_changes enable row level security;
revoke all on public.invoice_stores, public.invoice_store_location_changes from anon, authenticated;

