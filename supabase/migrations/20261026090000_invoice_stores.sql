create or replace function public.list_invoice_stores(p_token text)
returns json
language plpgsql
stable
security definer
set search_path = ''
as $$
begin
  perform private.check_token(p_token);
  return coalesce((
    select json_agg(private.invoice_store_json(s.id) order by lower(s.name), s.code)
    from public.invoice_stores s
  ), '[]'::json);
end;
$$;

-- Si el código ya está registrado devuelve ese registro sin cambiarlo (created = false).
create or replace function public.register_invoice_store(
  p_token   text,
  p_code    text,
  p_name    text,
  p_address text default null,
  p_notes   text default null
)
returns json
language plpgsql
volatile
security definer
set search_path = ''
as $$
declare
  v_code text := trim(coalesce(p_code, ''));
  v_name text := left(trim(coalesce(p_name, '')), 200);
  v_id   bigint;
begin
  perform private.check_token(p_token);

  if v_code = '' or length(v_code) > 50 then
    raise exception 'VALIDATION_ERROR' using hint = 'code: el código es obligatorio (hasta 50 caracteres).';
  end if;
  if v_name = '' then
    raise exception 'VALIDATION_ERROR' using hint = 'name: el nombre es obligatorio.';
  end if;

  insert into public.invoice_stores (code, name, address, notes)
  values (
    v_code,
    v_name,
    nullif(left(trim(p_address), 500), ''),
    nullif(left(trim(p_notes), 2000), '')
  )
  on conflict (ltrim(code, '0')) do nothing
  returning id into v_id;

  if v_id is not null then
    return json_build_object('store', private.invoice_store_json(v_id), 'created', true);
  end if;
  select id into v_id from public.invoice_stores where ltrim(code, '0') = ltrim(v_code, '0');
  return json_build_object('store', private.invoice_store_json(v_id), 'created', false);
end;
$$;

create or replace function public.list_invoice_store_location_changes(p_token text, p_store_id bigint)
returns json
language plpgsql
stable
security definer
set search_path = ''
as $$
begin
  perform private.check_token(p_token);
  if not exists (select 1 from public.invoice_stores where id = p_store_id) then
    raise exception 'STORE_NOT_FOUND' using hint = format('No existe un registro por factura con id %s.', p_store_id);
  end if;
  return coalesce((
    select json_agg(row_to_json(c) order by c.created_at desc, c.id desc)
    from public.invoice_store_location_changes c
    where c.invoice_store_id = p_store_id
  ), '[]'::json);
end;
$$;

-- Igual que register_store_location: solo la ubicación actual del teléfono (GPS).
create or replace function public.register_invoice_store_location(
  p_token      text,
  p_store_id   bigint,
  p_latitude   double precision,
  p_longitude  double precision,
  p_source     text,
  p_accuracy_m double precision default null
)
returns json
language plpgsql
volatile
security definer
set search_path = ''
as $$
declare
  v_store  public.invoice_stores%rowtype;
  v_change public.invoice_store_location_changes%rowtype;
begin
  perform private.check_token(p_token);

  if p_latitude is null or p_latitude not between -90 and 90 or p_latitude = 'NaN'::float8 then
    raise exception 'VALIDATION_ERROR' using hint = 'latitude: debe estar entre -90 y 90.';
  end if;
  if p_longitude is null or p_longitude not between -180 and 180 or p_longitude = 'NaN'::float8 then
    raise exception 'VALIDATION_ERROR' using hint = 'longitude: debe estar entre -180 y 180.';
  end if;
  if p_source is distinct from 'gps' then
    raise exception 'VALIDATION_ERROR' using hint = 'source: solo se puede registrar la ubicación actual (gps).';
  end if;
  if p_accuracy_m is not null and (p_accuracy_m not between 0 and 100000 or p_accuracy_m = 'NaN'::float8) then
    raise exception 'VALIDATION_ERROR' using hint = 'accuracyM: debe estar entre 0 y 100000.';
  end if;

  select * into v_store from public.invoice_stores where id = p_store_id for update;
  if not found then
    raise exception 'STORE_NOT_FOUND' using hint = format('No existe un registro por factura con id %s.', p_store_id);
  end if;

  insert into public.invoice_store_location_changes
    (invoice_store_id, latitude, longitude, accuracy_m, source, previous_latitude, previous_longitude)
  values
    (p_store_id, p_latitude, p_longitude, p_accuracy_m, p_source, v_store.latitude, v_store.longitude)
  returning * into v_change;

  update public.invoice_stores
  set latitude = p_latitude, longitude = p_longitude, location_updated_at = v_change.created_at
  where id = p_store_id;

  return json_build_object('store', private.invoice_store_json(p_store_id), 'change', row_to_json(v_change));
end;
$$;

-- Igual que delete_store_location_change: el registro siguiente hereda la coordenada "anterior";
-- si se borra el más reciente, el registro vuelve a la coordenada anterior.
create or replace function public.delete_invoice_store_location_change(
  p_token     text,
  p_store_id  bigint,
  p_change_id bigint
)
returns json
language plpgsql
volatile
security definer
set search_path = ''
as $$
declare
  v_change public.invoice_store_location_changes%rowtype;
  v_newer  bigint;
  v_latest timestamptz;
begin
  perform private.check_token(p_token);

  perform 1 from public.invoice_stores where id = p_store_id for update;
  if not found then
    raise exception 'STORE_NOT_FOUND' using hint = format('No existe un registro por factura con id %s.', p_store_id);
  end if;

  select * into v_change from public.invoice_store_location_changes
  where id = p_change_id and invoice_store_id = p_store_id;
  if not found then
    raise exception 'CHANGE_NOT_FOUND'
      using hint = format('El registro %s no tiene un cambio de ubicación con id %s.', p_store_id, p_change_id);
  end if;

  select id into v_newer from public.invoice_store_location_changes
  where invoice_store_id = p_store_id
    and (created_at > v_change.created_at or (created_at = v_change.created_at and id > v_change.id))
  order by created_at, id
  limit 1;

  delete from public.invoice_store_location_changes where id = v_change.id;

  if v_newer is not null then
    update public.invoice_store_location_changes
    set previous_latitude = v_change.previous_latitude, previous_longitude = v_change.previous_longitude
    where id = v_newer;
  else
    select max(created_at) into v_latest from public.invoice_store_location_changes where invoice_store_id = p_store_id;
    update public.invoice_stores
    set latitude = v_change.previous_latitude,
        longitude = v_change.previous_longitude,
        location_updated_at = v_latest
    where id = p_store_id;
  end if;

  return json_build_object('store', private.invoice_store_json(p_store_id));
end;
$$;

